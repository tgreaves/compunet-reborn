/*
 * button_images.c — supply the directory/frame button gadget images.
 *
 * The gadget Image structs live in the extracted data blob (directory action buttons
 * at 0x11e212, frame buttons at 0x11fa6e), but their ImageData fields hold literal
 * absolute pointers (0x116000 / 0x116200) into a graphics hunk that assumed the
 * original load address 0x100000. Our reconstruction never reproduced that hunk and is
 * loaded elsewhere by AmigaDOS, so those pointers are garbage and DrawImage blits noise
 * (the corrupted buttons). Here we embed the original 60x16x4 / 50x16x4 bitmaps
 * (extracted verbatim from the binary at 0x116000 / 0x116200), copy them into Chip RAM
 * (the blitter DrawImage uses can only DMA from Chip), and patch each Image.ImageData to
 * the Chip copy. Same pattern as the busy-pointer sprite fix in ui.c.
 */
