/* Copy 'src' into Chip RAM and store the Chip pointer into the Image's ImageData field. */
static void patch_image(APTR image, const UBYTE *src, ULONG size)
{
    APTR chip = AllocMem(size, MEMF_CHIP);   /* never freed: lives for the program's life */
    if (chip == NULL)
        return;
    CopyMem((APTR)src, chip, size);
    *(APTR *)((UBYTE *)image + IMG_DATA_OFF) = chip;
}

/*
 * init_button_images — repoint the shared directory-action and frame button Images to
 * Chip-RAM copies of their real bitmaps. Idempotent; call before either window opens.
 */
void init_button_images(void)
{
    static BYTE done = 0;
    if (done)
        return;
    done = 1;
    patch_image(DATA(0x11e212), action_btn_img, sizeof action_btn_img);  /* dir action buttons */
    patch_image(DATA(0x11fa6e), frame_btn_img,  sizeof frame_btn_img);   /* frame buttons      */
}
